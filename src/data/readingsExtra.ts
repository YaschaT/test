import type { ReadingPassage, ReadingQuestion, Translatable } from '../types';
import { s } from './textHelpers';

/**
 * Extended graded-reader library — original short "books" for the Tadoku-style
 * extensive-reading section. Spread into READINGS in ./readings.ts.
 *
 * Graded on Tadoku's own Level 0–5 scale (see TadokuLevel). Levels 0–1 are pure
 * extensive reading (no comprehension quiz — `questions: []`); Levels 2+ carry a
 * short optional check. All text is hand-authored for this app; vocab/grammar
 * highlight ids point at real items already in the app so every link resolves.
 */

function rs(
  segments: { text: string; reading?: string }[],
  kana: string,
  romaji: string,
  en: string,
  nl: string,
) {
  return { segments, kana, romaji, en, nl };
}

function q(
  id: string,
  question: Translatable,
  options: Translatable[],
  correctIndex: number,
): ReadingQuestion {
  return { id, question, options, correctIndex };
}

